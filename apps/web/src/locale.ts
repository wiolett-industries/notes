/** Exact known errors retain detail; unknown localized/native errors get a safe UI fallback. */
export function localizeError(error: unknown, language: Locale = locale): string {
  const message = error instanceof Error ? error.message : typeof error === 'string' ? error : '';
  const limit = quotaLimit(message);
  if (limit !== null) return quotaMessage(limit, language);
  if (Object.hasOwn(catalog, message)) return language === 'ru' ? message : catalog[message as Key];
  if (Object.values(catalog).includes(message as never)) {
    if (language === 'en') return message;
    return Object.keys(catalog).find(key => catalog[key as Key] === message)!;
  }
  return translate(language, 'Не удалось выполнить действие. Попробуйте снова.');
}
/** Recognize the configured quota message in either UI language. */
function quotaLimit(message: string): number | null {
  const match = /^Достигнут лимит доски — ([\d.,]+) МБ\. Удалите часть данных или отключите публичный снимок\.$/.exec(message)
    ?? /^The board has reached its ([\d.,]+) MB limit\. Delete some data or disable the public snapshot\.$/.exec(message);
  if (!match) return null;
  const value = Number(match[1].replace(',', '.'));
  return Number.isFinite(value) && value > 0 ? value * 1e6 : null;
}
export function isStorageLimit(message: string): boolean { return quotaLimit(message) !== null; }
export function quotaMessage(limitBytes: number, language: Locale = locale): string {
  return translate(language, 'Достигнут лимит доски — {limit} МБ. Удалите часть данных или отключите публичный снимок.', {
    limit: (limitBytes / 1e6).toLocaleString(language, { useGrouping: false, maximumFractionDigits: 6 }),
  });
}
export function storageUsage(usedBytes: number, limitBytes: number, language: Locale = locale): string {
  return translate(language, '{used} / {limit} МБ', {
    used: (usedBytes / 1e6).toLocaleString(language, { minimumFractionDigits: 1, maximumFractionDigits: 1 }),
    limit: (limitBytes / 1e6).toLocaleString(language, { useGrouping: false, maximumFractionDigits: 6 }),
  });
}
