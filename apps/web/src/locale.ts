export type Locale = 'ru' | 'en';
export function detectLocale(languages: readonly string[] = []): Locale {
  for (const language of languages) {
    const base = language.toLowerCase().split(/[-_]/)[0];
    if (base === 'ru' || base === 'en') return base;
  }
  return 'en';
}
export const locale = detectLocale(typeof navigator === 'undefined' ? [] : navigator.languages?.length ? navigator.languages : [navigator.language]);
export function applyDocumentLocale(target: Pick<Document, 'documentElement'> = document) { target.documentElement.lang = locale; }

type Key = keyof typeof catalog;
type Placeholders<S extends string> = S extends `${string}{${infer P}}${infer Rest}` ? P | Placeholders<Rest> : never;
type Args<K extends Key> = [Placeholders<K>] extends [never] ? [] : [values: Record<Placeholders<K>, string | number>];
export function translate<K extends Key>(language: Locale, key: K, ...args: Args<K>): string {
  const text = language === 'ru' ? key : catalog[key];
  const values = args[0] as Record<string, string | number> | undefined;
  // Callback replacement preserves literal $&, braces, and markup in user values.
  // Render the result as text in JSX; HTML-producing consumers must escape it.
  return text.replace(/\{(\w+)\}/g, (match, name: string) => values && name in values ? String(values[name]) : match);
}
export function t<K extends Key>(key: K, ...args: Args<K>): string { return translate(locale, key, ...args); }

